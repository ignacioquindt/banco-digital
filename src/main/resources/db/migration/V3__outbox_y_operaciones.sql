-- Migracion V3: Transactional Outbox Pattern y Operaciones de Fondos (Cash-in / Cash-out)

CREATE TABLE IF NOT EXISTS outbox_eventos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    aggregate_type VARCHAR(50) NOT NULL,
    aggregate_id VARCHAR(100) NOT NULL,
    event_type VARCHAR(100) NOT NULL,
    payload TEXT NOT NULL,
    correlation_id VARCHAR(64),
    estado VARCHAR(20) NOT NULL DEFAULT 'PENDIENTE',
    reintentos INT NOT NULL DEFAULT 0,
    creado_en TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    procesado_en TIMESTAMP WITH TIME ZONE
);

CREATE INDEX IF NOT EXISTS idx_outbox_estado ON outbox_eventos(estado, creado_en);

CREATE TABLE IF NOT EXISTS operaciones_cuenta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cuenta_id BIGINT NOT NULL REFERENCES cuentas(id),
    tipo VARCHAR(20) NOT NULL CHECK (tipo IN ('DEPOSITO', 'EXTRACCION')),
    importe NUMERIC(19,2) NOT NULL CHECK (importe > 0),
    saldo_posterior NUMERIC(19,2) NOT NULL CHECK (saldo_posterior >= 0),
    clave_idempotencia UUID NOT NULL UNIQUE,
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_operaciones_cuenta_fecha ON operaciones_cuenta(cuenta_id, fecha DESC);
