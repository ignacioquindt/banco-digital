CREATE TABLE IF NOT EXISTS usuarios (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 nombre VARCHAR(100) NOT NULL, email VARCHAR(254) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL, activo BOOLEAN NOT NULL DEFAULT TRUE,
 credenciales_version BIGINT NOT NULL DEFAULT 0
);
ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS credenciales_version BIGINT NOT NULL DEFAULT 0;
CREATE TABLE IF NOT EXISTS cuentas (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 numero_cuenta VARCHAR(20) NOT NULL UNIQUE,
 moneda VARCHAR(3) NOT NULL DEFAULT 'ARS' CHECK (moneda='ARS'),
 saldo NUMERIC(19,2) NOT NULL DEFAULT 0 CHECK (saldo>=0),
 usuario_id BIGINT REFERENCES usuarios(id)
);
ALTER TABLE cuentas ADD COLUMN IF NOT EXISTS usuario_id BIGINT REFERENCES usuarios(id);
CREATE INDEX IF NOT EXISTS idx_cuentas_usuario_id ON cuentas(usuario_id);
CREATE TABLE IF NOT EXISTS transferencias (
 id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 origen_id BIGINT NOT NULL REFERENCES cuentas(id),
 destino_id BIGINT NOT NULL REFERENCES cuentas(id),
 importe NUMERIC(19,2) NOT NULL CHECK (importe>0),
 fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
 clave_idempotencia UUID NOT NULL UNIQUE,
 CHECK (origen_id<>destino_id)
);
ALTER TABLE transferencias ADD COLUMN IF NOT EXISTS clave_idempotencia UUID;
UPDATE transferencias SET clave_idempotencia=gen_random_uuid() WHERE clave_idempotencia IS NULL;
ALTER TABLE transferencias ALTER COLUMN clave_idempotencia SET NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS ux_transferencias_clave ON transferencias(clave_idempotencia);
CREATE INDEX IF NOT EXISTS idx_transferencias_origen_fecha ON transferencias(origen_id,fecha DESC);
CREATE INDEX IF NOT EXISTS idx_transferencias_destino_fecha ON transferencias(destino_id,fecha DESC);
CREATE TABLE IF NOT EXISTS recuperacion_tokens (
 hash VARCHAR(64) PRIMARY KEY,
 usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
 vence TIMESTAMP WITH TIME ZONE NOT NULL,
 usado BOOLEAN NOT NULL DEFAULT FALSE,
 credenciales_version BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS idx_recuperacion_vence ON recuperacion_tokens(vence);
