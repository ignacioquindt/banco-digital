-- Migracion V2: Soporte para roles de usuario y tabla de auditoria transaccional

ALTER TABLE usuarios ADD COLUMN IF NOT EXISTS rol VARCHAR(20) NOT NULL DEFAULT 'ROLE_CLIENTE';

CREATE TABLE IF NOT EXISTS auditoria_operaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT,
    email VARCHAR(254),
    operacion VARCHAR(100) NOT NULL,
    detalle TEXT,
    ip VARCHAR(45),
    correlation_id VARCHAR(64),
    fecha TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    exito BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX IF NOT EXISTS idx_auditoria_usuario_fecha ON auditoria_operaciones(usuario_id, fecha DESC);
CREATE INDEX IF NOT EXISTS idx_auditoria_correlation ON auditoria_operaciones(correlation_id);
